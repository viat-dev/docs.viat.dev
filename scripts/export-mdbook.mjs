import { mkdir, readFile, writeFile, rm, lstat } from 'node:fs/promises';
import path from 'node:path';
import { ROOT, LOCALES, readPages, pairErrors, resolveMarkdownLink } from './lib/content.mjs';
import { inspectMarkdown } from './lib/markdown.mjs';
import { publicUrl } from './lib/site.mjs';

// Export only the allowlisted content tree, never the product docs directory
// with its private feedback and historical plans. Deployment is a separate step.
const output = path.join(ROOT, 'exports/mdbook');
const marker = '.viat-generated-book';
const pages = (await readPages()).filter((p) => p.data.channel === 'stable');
const errors = pairErrors(pages);
if (errors.length) throw new Error(errors.join('\n'));
const manifest = JSON.parse(await readFile(path.join(ROOT, 'contracts/manifest.json'), 'utf8'));
for (const directory of [path.dirname(output), output]) {
  try {
    const info = await lstat(directory);
    if (info.isSymbolicLink() || !info.isDirectory()) throw new Error(`Not a real output directory: ${directory}`);
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
}
try {
  await lstat(output);
  await readFile(path.join(output, marker));
  await rm(output, { recursive: true });
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  // An existing unmarked directory is not ours to erase.
  try { await lstat(output); throw new Error('Refusing to replace an unmarked book directory'); }
  catch (check) { if (check.code !== 'ENOENT') throw check; }
}
await mkdir(path.join(output, 'src'), { recursive: true });
await writeFile(path.join(output, marker), 'Generated by scripts/export-mdbook.mjs\n');
// mdBook otherwise inserts <base href="/"> into 404.html. An empty site URL
// keeps assets and same-page anchors relative under either supported mount.
await writeFile(path.join(output, 'book.toml'), `[book]\ntitle = "Viat ${manifest.edition} / 产品手册"\nlanguage = "en"\nsrc = "src"\n\n[output.html]\ndefault-theme = "light"\npreferred-dark-theme = "navy"\nno-section-label = true\nsite-url = ""\n`);

const summary = ['# Summary', '', '- [Edition / 版本](README.md)'];
const english = pages.filter((p) => p.locale === 'en');
for (const locale of LOCALES) {
  summary.push('', `# ${locale === 'zh-cn' ? '简体中文' : 'English'}`, '');
  for (const page of pages.filter((p) => p.locale === locale)) {
    // A root-absolute website URL would leave /viat/_docs/ when served offline.
    // Plain source-relative Markdown links retain their directory layout.
    let body = page.content;
    const inspection = await inspectMarkdown(page);
    const replacements = inspection.links.filter((link) => link.url.startsWith('/') && !link.url.startsWith('//'));
    for (const link of replacements.sort((a, b) => b.position.start.offset - a.position.start.offset)) {
      // Offsets refer to the untrimmed source, so defer trimming until after edits.
      const start = link.position.start.offset, end = link.position.end.offset;
      const chunk = body.slice(start, end);
      const index = chunk.lastIndexOf(link.url);
      if (index < 0) throw new Error(`${page.relative}: cannot safely rewrite root link ${link.url}`);
      const resolved = resolveMarkdownLink(page.relative, link.url);
      const replacement = resolved
        ? path.posix.relative(path.posix.dirname(page.relative), resolved.target) + resolved.suffix
        : publicUrl(link.url);
      body = body.slice(0, start + index) + replacement + body.slice(start + index + link.url.length);
    }
    const title = body.trimStart().startsWith('# ') ? '' : `# ${page.data.title}\n\n`;
    const notice = locale === 'zh-cn'
      ? `核验版本：${page.data.verified_release}；文档 ID：${page.data.doc_id}。`
      : `Verified release: ${page.data.verified_release}; document ID: ${page.data.doc_id}.`;
    const target = path.join(output, 'src', page.relative);
    await mkdir(path.dirname(target), { recursive: true });
    const example = page.data.doc_id.startsWith('applications.') ? page.data.doc_id.slice('applications.'.length) : null;
    const download = example ? `\n\n[${locale === 'zh-cn' ? '完整示例文件' : 'Complete example files'}](${path.posix.relative(path.posix.dirname(page.relative), `examples/${example}/index.html`)})\n` : '';
    await writeFile(target, `${title}> ${notice}\n\n${body.trim()}${download}\n`);
    summary.push(`- [${page.data.title.replaceAll('[', '').replaceAll(']', '')}](${page.relative})`);
  }
}

// Compatibility pages are generated indexes, not a second hand-maintained manual.
// Their symbol index keeps product pin tests useful during the path migration;
// every symbol points to the detailed chapter from which it was extracted.
for (const [filename, prefix, heading, symbolPattern] of [
  ['configuration.md', 'configuration/', 'Configuration', /\b(?:VIAT_[A-Z0-9_]+|DATABASE_URL|SCHEDULER_ENABLED)\b/g],
  ['scripting.md', 'assets/scripts/', 'Scripting', /\b(?:python|sql|typescript|shell|graphql|viat_gql|llm|rust|binary)\b/g],
  ['worker-protocol.md', 'assets/scripts/worker-protocol.md', 'Worker protocol', null],
]) {
  const chapters = english.filter((p) => p.localPath.startsWith(prefix));
  if (!chapters.length) continue;
  const lines = [`# ${heading}`, '', '> Generated compatibility index. Follow a chapter for requirements, defaults and limitations.', ''];
  const symbols = new Map();
  for (const chapter of chapters) {
    lines.push(`- [${chapter.data.title}](${chapter.relative})`);
    if (symbolPattern) for (const match of chapter.content.matchAll(symbolPattern)) if (!symbols.has(match[0])) symbols.set(match[0], chapter);
  }
  if (symbols.size) {
    lines.push('', '## Documented identifiers', '', '| Identifier | Reference |', '| --- | --- |');
    for (const [name, chapter] of [...symbols].sort(([a], [b]) => a.localeCompare(b, 'en'))) lines.push(`| \`${name}\` | [${chapter.data.title}](${chapter.relative}) |`);
  }
  await writeFile(path.join(output, 'src', filename), lines.join('\n') + '\n');
  summary.push(`\n- [${heading} — compatibility index](${filename})`);
}
await writeFile(path.join(output, 'src/SUMMARY.md'), summary.join('\n') + '\n');
await writeFile(path.join(output, 'src/README.md'), [
  '# Viat product handbook / 产品手册', '',
  `Server/CLI **${manifest.server.version}**; client **${manifest.client.version}**, independently versioned.`, '',
  manifest.publication_ready ? 'Release-pinned handbook / 随版本固定的手册。' : '**Reconstruction preview, not a complete release. / 重建预览，尚非完整发布。**', '',
  '[简体中文](zh-cn/index.md) · [English](en/index.md)', '',
  'All chapters and the default book assets work without a network connection. Links to the online LLM index, providers and external references still require network access.', '',
  '正文和书籍默认资源不要求联网。在线 LLM 索引、提供商和外部参考链接仍需要网络。', '',
].join('\n'));
await writeFile(path.join(output, 'provenance.json'), JSON.stringify({ edition: manifest.edition, source: manifest.contract_bundle.source_sha, candidate: !manifest.publication_ready, pages: pages.length }, null, 2) + '\n');
console.log(`Exported ${pages.length} stable pages to exports/mdbook. Not synced to the product repository.`);
